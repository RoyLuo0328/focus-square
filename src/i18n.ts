export type Locale = keyof typeof messages;
export type Translator = (key: keyof (typeof messages)["en"]) => string | ((...args: number[]) => string);

export function resolveLocale(settings: AppSettings): Locale {
  if (settings.locale === "zh-CN" || settings.locale === "en") return settings.locale;
  return navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

export function translator(locale: Locale): Translator {
  return (key) => messages[locale][key] as string | ((...args: number[]) => string);
}

export function modeLabel(mode: TimerMode, t: Translator): string {
  return String(t(mode));
}

export function statusLabel(status: TimerStatus, t: Translator): string {
  return String(t(status));
}
